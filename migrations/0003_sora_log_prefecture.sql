-- 0003_sora_log_prefecture.sql
-- ------------------------------------------------------------
-- 「そらのようす」の記録に、任意の都道府県を追加する(2026-11-13、
-- Decision Log 0218)。「記録を見る」を日本地図で見せたいとの指示を
-- 受けたもの。都道府県は任意項目(選ばなくても記録できる)。
--
-- 市区町村・GPS座標などの詳細な位置情報は引き続き収集しない
-- (Decision Log 0216の方針を維持)。都道府県という大きな行政区分の
-- みを、記録者が自己申告する形で追加する。
-- ------------------------------------------------------------
ALTER TABLE sora_log_entries ADD COLUMN prefecture TEXT CHECK (
  prefecture IS NULL OR prefecture IN (
    '北海道','青森県','岩手県','宮城県','秋田県','山形県','福島県',
    '茨城県','栃木県','群馬県','埼玉県','千葉県','東京都','神奈川県',
    '新潟県','富山県','石川県','福井県','山梨県','長野県','岐阜県',
    '静岡県','愛知県','三重県','滋賀県','京都府','大阪府','兵庫県',
    '奈良県','和歌山県','鳥取県','島根県','岡山県','広島県','山口県',
    '徳島県','香川県','愛媛県','高知県','福岡県','佐賀県','長崎県',
    '熊本県','大分県','宮崎県','鹿児島県','沖縄県'
  )
);

CREATE INDEX IF NOT EXISTS idx_sora_log_prefecture ON sora_log_entries (status, prefecture);
